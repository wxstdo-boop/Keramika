import 'package:flutter/painting.dart';

/// Стиль ОТДЕЛЬНОГО символа. Реализуется контроллерами, которым нужно
/// рисовать часть текста другим шрифтом, чем весь остальной текст.
///
/// Важно, что такое правило применяется ОДНОВРЕМЕННО и в самом поле (там
/// считается раскладка, курсор и выделение), и в слое плавных букв
/// `SmoothTyping` — иначе нарисованный текст разъедется с курсором. Поэтому
/// интерфейс общий, а не спрятан внутри одного из них.
abstract interface class GlyphStyling {
  /// Стиль для одного символа [glyph] на основе общего стиля [base].
  TextStyle styleForGlyph(TextStyle base, String glyph);
}
